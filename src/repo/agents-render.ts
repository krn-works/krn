// AGENTS.md rendering.
import { readdir, readFile } from 'node:fs/promises';
import { z } from 'zod';
import { readJson } from './json-text.ts';

export type Rule = {
  id: string;
  trigger: string;
  action: string;
  owner: string;
  /** `lead`: governance and process rules a worker session never sees. */
  audience?: 'lead';
  enforcement: {
    kind: 'test' | 'gate' | 'none';
    check: string;
    deadline?: string;
  };
  rationale: string;
};

const packageScripts = z.object({ scripts: z.record(z.string(), z.string()) });
const registry = z.object({ rules: z.array(z.custom<Rule>()) });

/** The rules in spec/rules.json under the repository root. */
export async function loadRules(root: URL): Promise<Rule[]> {
  return registry.parse(
    readJson(await readFile(new URL('spec/rules.json', root), 'utf8')),
  ).rules;
}

function renderRule(rule: Rule): string {
  return `- **${rule.id}** When ${rule.trigger}, ${rule.action} _(owner: ${rule.owner}; ${rule.enforcement.kind}: ${rule.enforcement.check}; ${rule.rationale})_`;
}

/** The lead file carries only what the lead acts on: the owner, check and rationale stay in spec/rules.json. */
function renderAction(rule: Rule): string {
  return `- **${rule.id}** When ${rule.trigger}, ${rule.action}`;
}

/**
 * The rules the lead file renders: a worker scope prohibition a test enforces
 * is owned by that test, so it costs the lead bytes without changing an action.
 */
export function leadRules(all: readonly Rule[]): Rule[] {
  return all.filter(
    (rule) => rule.audience === 'lead' || rule.enforcement.kind !== 'test',
  );
}

/** The rules a worker session sees: scope prohibitions stay, lead and governance rules go. */
export function workerRules(all: readonly Rule[], testFirst = true): Rule[] {
  const rules = all.filter((rule) => rule.audience !== 'lead');
  return testFirst ? [...rules, TEST_FIRST] : rules;
}

/** On by default: a worker's rule list gains the test-first rule the Stop hook enforces. */
export const TEST_FIRST: Rule = {
  id: 'KRN-TF',
  trigger: 'a worker changes source',
  action:
    'the worker MUST prove red at base: commit a test that fails against the base source and passes on its commit',
  owner: 'worker',
  enforcement: {
    kind: 'test',
    check: 'src/hook/stop.ts unless KRN_TEST_FIRST=0',
  },
  rationale: 'A red test, not tracker state, defines done',
};

/** `worker` omits the lead's workflow paragraph: it is a positive process directive. */
export function render(selected: readonly Rule[], worker = false): string {
  return [
    '<!-- Generated by scripts/render-agents.ts from spec/rules.json. -->',
    '<!-- krn-agent-workflow:start -->',
    '# KRN repository rules',
    '',
    ...(worker
      ? []
      : [
          'This file is already loaded as CLAUDE.md; do not read it again. Small change: edit, run `npm run fast` once (biome --write, tsc, related tests, one verdict: `fast PASS:` or `fast FAIL (...):`; run it as a background shell and wait for its exit, never an until/while sleep loop on its log), commit; CI runs the rest.',
          '',
        ]),
    ...(worker
      ? selected.map(renderRule)
      : leadRules(selected).map(renderAction)),
    '<!-- krn-agent-workflow:end -->',
    '',
  ].join('\n');
}

export async function checkRegistry(
  root: URL,
  rules: readonly Rule[],
): Promise<string[]> {
  const { scripts } = packageScripts.parse(
    readJson(await readFile(new URL('package.json', root), 'utf8')),
  );
  const testFiles = await readdir(new URL('test/', root), { recursive: true });
  const testSources = await Promise.all(
    testFiles
      .filter((file) => /\.test\.[cm]?[jt]s$/u.test(file))
      .map((file) => readFile(new URL(`test/${file}`, root), 'utf8')),
  );
  const titles = new Set(
    testSources.flatMap((source) =>
      [...source.matchAll(/\btest\(\s*['"]([^'"]+)['"]/gu)].map(
        (match) => match[1],
      ),
    ),
  );
  const errors: string[] = [];
  for (const rule of rules) {
    const { kind, check } = rule.enforcement;
    if (kind === 'test' && !titles.has(check))
      errors.push(`${rule.id} names missing test: ${check}`);
    if (
      kind === 'gate' &&
      !Object.hasOwn(scripts, check.replace(/^npm run /u, ''))
    )
      errors.push(`${rule.id} names missing gate script: ${check}`);
    if (kind === 'none' && rule.enforcement.deadline === undefined)
      errors.push(`${rule.id} none enforcement needs a migration deadline`);
  }
  return errors;
}
