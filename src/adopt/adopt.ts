export interface AdoptOptions {
  /** Commit sha of krn-works/krn that holds the shared project-ci.yml; CI is written only when given. */
  ref?: string;
  /** Seed tasks/ with the tracker; implied by `ref`. */
  tracker?: boolean;
  install?: string;
  lint?: string;
  typecheck?: string;
  test?: string;
}

export interface AdoptionReport {
  written: string[];
  unchanged: string[];
  /** Files not written, each with its reason. */
  skipped: string[];
}

const sharedWorkflow = 'krn-works/krn/.github/workflows/project-ci.yml';
const rulesStart = '<!-- krn-adoption:start -->';
const rulesEnd = '<!-- krn-adoption:end -->';

const adoptedRules: readonly string[] = [
  '**R-1** When work is managed, the lead MUST keep task status in `tasks/<id>.json` with `krn task`; workers MUST NOT edit tracker files.',
  '**R-2** When agent state is written, the author MUST keep it under `.krn/`, which is ignored by git.',
  '**R-3** When a change is ready, the author MUST obtain a green `ci / Check` on the exact HEAD; the repository has no other required gate.',
  '**R-4** When a commit completes a managed task, its last trailer paragraph MUST carry `Ticket: <id>` (`Refs: <id>` while the task stays open).',
];

export function renderRules(): string {
  return [
    rulesStart,
    '<!-- Generated by `krn adopt`; rerun it to refresh this block. -->',
    '# Delivery rules',
    '',
    ...adoptedRules.map((rule) => `- ${rule}`),
    rulesEnd,
    '',
  ].join('\n');
}

function quoted(value: string): string {
  return JSON.stringify(value);
}

export function renderWorkflow(
  options: AdoptOptions & { ref: string },
  name = 'CI',
  base = 'main',
): string {
  if (!/^[0-9a-f]{40}$/u.test(options.ref))
    throw new Error('--ref must be a full 40-character commit sha');
  const inputs = (
    [
      ['install', options.install],
      ['lint', options.lint],
      ['typecheck', options.typecheck],
      ['test', options.test],
    ] as const
  ).flatMap(([name, value]) =>
    value === undefined || value === ''
      ? []
      : [`      ${name}: ${quoted(value)}`],
  );
  return [
    `name: ${name}`,
    '',
    'on:',
    '  push:',
    `    branches: [${base}]`,
    '  pull_request:',
    '',
    'permissions:',
    '  contents: read',
    '',
    'jobs:',
    '  ci:',
    `    uses: ${sharedWorkflow}@${options.ref}`,
    ...(inputs.length > 0 ? ['    with:', ...inputs] : []),
    '',
  ].join('\n');
}

/**
 * The CI call with inputs from the flags, else from the written contract (krn.json or detection):
 * the shared workflow refuses a call without lint, typecheck or test. Pushes run on the contract
 * base. Undefined, with a skipped line, when no command is known.
 */
function ciWorkflow(
  root: string,
  options: AdoptOptions & { ref: string },
  report: AdoptionReport,
): string | undefined {
  let contract: RepoContract | undefined;
  try {
    contract = findContract(root)?.contract;
  } catch {
    contract = undefined;
  }
  const install = options.install ?? contract?.install;
  const test = options.test ?? contract?.test;
  const inputs = {
    ...options,
    ...(install === undefined ? {} : { install }),
    ...(test === undefined ? {} : { test }),
  };
  const path = workflowPath(root);
  if (!inputs.lint && !inputs.typecheck && !inputs.test) {
    report.skipped.push(
      `${path} (no lint, typecheck or test command; pass --test CMD)`,
    );
    return undefined;
  }
  return renderWorkflow(
    inputs,
    path.endsWith('krn-ci.yml') ? 'KRN CI' : 'CI',
    contract?.base ?? 'main',
  );
}

function writeIfChanged(
  root: string,
  relative: string,
  content: string,
  report: AdoptionReport,
): void {
  const path = join(root, relative);
  if (existsSync(path) && readFileSync(path, 'utf8') === content) {
    report.unchanged.push(relative);
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  report.written.push(relative);
}

/**
 * The shared CI call goes to `ci.yml` unless the repository already has its own
 * `ci.yml`; that one keeps running and the call goes to `krn-ci.yml` beside it.
 */
function workflowPath(root: string): string {
  const ci = '.github/workflows/ci.yml';
  const path = join(root, ci);
  return existsSync(path) &&
    !readFileSync(path, 'utf8').includes(sharedWorkflow)
    ? '.github/workflows/krn-ci.yml'
    : ci;
}

/**
 * The caller job `ci` runs the shared workflow, whose aggregate job is `Check`,
 * so GitHub names the required check run `ci / <check>` (the App of the repository contract). `krn pr ship`
 * reads this selector from the PR base; an existing different policy is kept.
 */
const admissionPolicy = `${JSON.stringify(
  {
    schemaVersion: 1,
    checkRunName: `ci / ${REQUIRED_CHECK_NAME}`,
    appId: REQUIRED_CHECK_APP_ID,
  },
  null,
  2,
)}\n`;

function writeAdmission(root: string, report: AdoptionReport): void {
  const relative = 'spec/ci-admission.json';
  const path = join(root, relative);
  if (existsSync(path) && readFileSync(path, 'utf8') !== admissionPolicy) {
    report.skipped.push(`${relative} (an existing admission policy is kept)`);
    return;
  }
  writeIfChanged(root, relative, admissionPolicy, report);
}

function upsertRules(current: string): string {
  const block = renderRules();
  const start = current.indexOf(rulesStart);
  const end = current.indexOf(rulesEnd);
  if (start >= 0 && end > start)
    return `${current.slice(0, start)}${block}${current.slice(end + rulesEnd.length).replace(/^\n/u, '')}`;
  return current === '' ? block : `${current.replace(/\n*$/u, '\n')}\n${block}`;
}

function writeRuleFile(
  root: string,
  relative: string,
  standards: readonly Standard[],
  report: AdoptionReport,
): void {
  const path = join(root, relative);
  const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
  const next = upsertStandardsBlock(
    upsertRules(current),
    renderStandardsBlock(standards),
  );
  if (next === current) report.unchanged.push(relative);
  else {
    writeFileSync(path, next);
    report.written.push(relative);
  }
}

/** Rules and standards go to AGENTS.md; CLAUDE.md links to it, and a regular CLAUDE.md (which Claude reads instead) carries the blocks too. */
function writeRules(
  root: string,
  standards: readonly Standard[],
  report: AdoptionReport,
): void {
  writeRuleFile(root, 'AGENTS.md', standards, report);
  const link = join(root, 'CLAUDE.md');
  if (isSymlink(link)) report.unchanged.push('CLAUDE.md');
  else if (existsSync(link))
    writeRuleFile(root, 'CLAUDE.md', standards, report);
  else {
    symlinkSync('AGENTS.md', link);
    report.written.push('CLAUDE.md');
  }
}

function isSymlink(path: string): boolean {
  try {
    return lstatSync(path).isSymbolicLink();
  } catch {
    return false;
  }
}

function ignoreAgentState(root: string, report: AdoptionReport): void {
  const path = join(root, '.gitignore');
  const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
  const lines = new Set(current.split('\n').map((line) => line.trim()));
  // A venv the contract install creates inside every worktree is never a tracked input.
  const venv = /(?:^|[\s/])\.venv\b/u.test(installOf(root) ?? '');
  const missing = ['.krn/', ...(venv ? ['.venv/'] : [])].filter(
    (entry) => !lines.has(entry) && !lines.has(entry.slice(0, -1)),
  );
  if (missing.length === 0) {
    report.unchanged.push('.gitignore');
    return;
  }
  appendFileSync(
    path,
    `${current === '' || current.endsWith('\n') ? '' : '\n'}${missing.join('\n')}\n`,
  );
  report.written.push('.gitignore');
}

function installOf(root: string): string | undefined {
  try {
    return findContract(root)?.contract.install;
  } catch {
    return undefined;
  }
}

function seedTasks(root: string, report: AdoptionReport): void {
  if (existsSync(join(root, 'tasks'))) {
    report.unchanged.push('tasks');
    return;
  }
  createTask(root, {
    title: 'Require the ci / Check status on the default branch',
    priority: 1,
    body: [
      'Outcome: merging to the default branch needs a green `ci / Check` and auto-merge is enabled.',
      'Why: the adopted delivery rules treat that Check as the only gate.',
      'Proof: a pull request with a red Check stays unmerged.',
    ],
  });
  report.written.push('tasks');
}

/** krn.json from detection (the operator may edit it); an existing file is never touched. */
function writeContract(
  root: string,
  options: AdoptOptions,
  report: AdoptionReport,
): void {
  if (existsSync(join(root, CONTRACT_FILE))) {
    report.unchanged.push(CONTRACT_FILE);
    return;
  }
  const found = findContract(root);
  const candidates = found ? [] : subpackageCandidates(root);
  const test = options.test ?? found?.contract.test;
  if (test === undefined) {
    report.skipped.push(
      `${CONTRACT_FILE} (${
        candidates.length > 1
          ? `several packages hold a test command: ${candidates.map((c) => c.dir).join(', ')}; pass --test CMD or write it`
          : 'no test command detected; pass --test CMD or write it'
      })`,
    );
    return;
  }
  const { contract } = found ?? {};
  // Lane worktrees, the canary and the Stop gate run this install before the test command.
  const install =
    options.install ??
    (options.test === undefined ? contract?.install : undefined);
  const body = {
    base: contract?.base ?? detectBase(root),
    ...(install === undefined ? {} : { install }),
    test,
    ...(contract?.related && options.test === undefined
      ? { related: contract.related }
      : {}),
    ...(contract?.fast && options.test === undefined
      ? { fast: contract.fast }
      : {}),
    tracker: options.ref !== undefined || options.tracker ? 'krn' : 'none',
  };
  writeIfChanged(
    root,
    CONTRACT_FILE,
    `${JSON.stringify(body, null, 2)}\n`,
    report,
  );
}

const skillsSource = fileURLToPath(new URL('./skills/', import.meta.url));

/** The universal skills (no KRN-repository text), one SKILL.md per directory. */
export function universalSkills(): string[] {
  return readdirSync(skillsSource).sort();
}

/** Installs the universal skills under .agents/skills, linking .claude/skills to it when neither exists. */
function writeSkills(root: string, report: AdoptionReport): void {
  for (const name of universalSkills()) {
    const relative = join('.agents', 'skills', name, 'SKILL.md');
    writeIfChanged(
      root,
      relative,
      readFileSync(join(skillsSource, name, 'SKILL.md'), 'utf8'),
      report,
    );
  }
  const link = join(root, '.claude', 'skills');
  if (!existsSync(link) && !isSymlink(link)) {
    mkdirSync(dirname(link), { recursive: true });
    symlinkSync(join('..', '.agents', 'skills'), link);
    report.written.push('.claude/skills');
  } else report.unchanged.push('.claude/skills');
}

/**
 * The project's standards after adoption: the universal pack records that apply to its detected
 * stack (tracker records only with a tracker), then its own records. A malformed file or an own
 * record reusing a pack id refuses (exit 65) before anything is written.
 */
function projectStandards(root: string, options: AdoptOptions): Standard[] {
  const needs = new Set<Need>(
    options.ref !== undefined || options.tracker ? ['tracker'] : [],
  );
  const stack = detectStack(root)?.stack;
  return seedStandards(
    readPack(),
    readProject(root),
    stack === undefined
      ? { adopted: false, needs }
      : { stack, adopted: false, needs },
    PROJECT_STANDARDS,
  );
}

interface HookEntry {
  hooks?: { type?: string; command?: unknown }[];
}

/** The existing settings object, or an error naming the file; read before anything is written. */
function readSettings(root: string): Record<string, unknown> {
  const relative = '.claude/settings.json';
  const path = join(root, relative);
  if (!existsSync(path)) return {};
  try {
    const parsed: unknown = JSON.parse(readFileSync(path, 'utf8'));
    if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed))
      throw new Error('expected an object');
    return parsed as Record<string, unknown>;
  } catch (error) {
    throw new Error(
      `${relative}: ${(error as Error).message}; nothing was written, fix or remove the file and rerun`,
    );
  }
}

/** Adds the Stop hook that calls `krn hook stop` (failing closed without krn on PATH), keeping every other setting and hook. */
function writeHooks(
  root: string,
  settings: Record<string, unknown>,
  report: AdoptionReport,
): void {
  const relative = '.claude/settings.json';
  const hooks = (settings.hooks ?? {}) as Record<string, unknown>;
  const stop = Array.isArray(hooks.Stop) ? (hooks.Stop as HookEntry[]) : [];
  // An earlier adoption's bare command exits 127 without krn on PATH, which does not block.
  for (const entry of stop)
    for (const hook of entry.hooks ?? [])
      if (hook.command === legacyStopCommand) hook.command = stopCommand;
  if (
    !stop.some((entry) =>
      entry.hooks?.some((hook) => hook.command === stopCommand),
    )
  )
    stop.push({ hooks: [{ type: 'command', command: stopCommand }] });
  settings.hooks = { ...hooks, Stop: stop };
  writeIfChanged(
    root,
    relative,
    `${JSON.stringify(settings, null, 2)}\n`,
    report,
  );
}

/** Writes the adoption set into `root`, a git repository; reruns change nothing. */
export function adopt(root: string, options: AdoptOptions): AdoptionReport {
  if (!existsSync(join(root, '.git')))
    throw new Error(`${root} is not a git repository root`);
  const sub = detectSubpackage(root);
  if (sub !== undefined)
    options = {
      ...options,
      ...(options.install === undefined && sub.install
        ? { install: sub.install }
        : {}),
      ...(options.lint === undefined && sub.lint ? { lint: sub.lint } : {}),
      ...(options.typecheck === undefined && sub.typecheck
        ? { typecheck: sub.typecheck }
        : {}),
      test: options.test ?? sub.test,
    };
  const report: AdoptionReport = { written: [], unchanged: [], skipped: [] };
  if (options.ref !== undefined && !/^[0-9a-f]{40}$/u.test(options.ref))
    throw new Error('--ref must be a full 40-character commit sha');
  // Everything that can refuse runs before the first write.
  const settings = readSettings(root);
  const standards = projectStandards(root, options);
  if (options.ref !== undefined || options.tracker) seedTasks(root, report);
  writeContract(root, options, report);
  const workflow =
    options.ref === undefined
      ? undefined
      : ciWorkflow(root, { ...options, ref: options.ref }, report);
  writeHooks(root, settings, report);
  writeSkills(root, report);
  writeIfChanged(root, PROJECT_STANDARDS, formatStandards(standards), report);
  writeRules(root, standards, report);
  ignoreAgentState(root, report);
  const seeded = seedConventions(root, new Date().toISOString().slice(0, 10));
  if (seeded) report.written.push(seeded);
  else report.unchanged.push('conventions');
  if (workflow !== undefined) {
    writeIfChanged(root, workflowPath(root), workflow, report);
    writeAdmission(root, report);
  }
  return report;
}
