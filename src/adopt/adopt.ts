// The adoption set: what a repository needs so KRN delivery works there.
import {
  appendFileSync,
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { CONTRACT_FILE, detectBase, findContract } from '../repo/contract.ts';
import { createTask } from '../task/store.ts';
import { seedConventions } from './conventions.ts';

export interface AdoptOptions {
  /** Commit sha of krn-works/krn that holds the shared project-ci.yml; CI is written only when given. */
  ref?: string;
  /** Seed tasks/ with the tracker; implied by `ref`. */
  tracker?: boolean;
  install?: string;
  lint?: string;
  typecheck?: string;
  test?: string;
}

export interface AdoptionReport {
  written: string[];
  unchanged: string[];
  /** Files not written, each with its reason. */
  skipped: string[];
}

const sharedWorkflow = 'krn-works/krn/.github/workflows/project-ci.yml';
const rulesStart = '<!-- krn-adoption:start -->';
const rulesEnd = '<!-- krn-adoption:end -->';

const adoptedRules: readonly string[] = [
  '**R-1** When work is managed, the lead MUST keep task status in `tasks/<id>.json` with `krn task`; workers MUST NOT edit tracker files.',
  '**R-2** When agent state is written, the author MUST keep it under `.krn/`, which is ignored by git.',
  '**R-3** When a change is ready, the author MUST obtain a green `ci / Check` on the exact HEAD; the repository has no other required gate.',
  '**R-4** When a commit completes a managed task, its last trailer paragraph MUST carry `Ticket: <id>` (`Refs: <id>` while the task stays open).',
];

export function renderRules(): string {
  return [
    rulesStart,
    '<!-- Generated by `krn adopt`; rerun it to refresh this block. -->',
    '# Delivery rules',
    '',
    ...adoptedRules.map((rule) => `- ${rule}`),
    rulesEnd,
    '',
  ].join('\n');
}

function quoted(value: string): string {
  return JSON.stringify(value);
}

export function renderWorkflow(
  options: AdoptOptions & { ref: string },
): string {
  if (!/^[0-9a-f]{40}$/u.test(options.ref))
    throw new Error('--ref must be a full 40-character commit sha');
  const inputs = (
    [
      ['install', options.install],
      ['lint', options.lint],
      ['typecheck', options.typecheck],
      ['test', options.test],
    ] as const
  ).flatMap(([name, value]) =>
    value === undefined || value === ''
      ? []
      : [`      ${name}: ${quoted(value)}`],
  );
  return [
    'name: CI',
    '',
    'on:',
    '  push:',
    '    branches: [main]',
    '  pull_request:',
    '',
    'permissions:',
    '  contents: read',
    '',
    'jobs:',
    '  ci:',
    `    uses: ${sharedWorkflow}@${options.ref}`,
    ...(inputs.length > 0 ? ['    with:', ...inputs] : []),
    '',
  ].join('\n');
}

function writeIfChanged(
  root: string,
  relative: string,
  content: string,
  report: AdoptionReport,
): void {
  const path = join(root, relative);
  if (existsSync(path) && readFileSync(path, 'utf8') === content) {
    report.unchanged.push(relative);
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  report.written.push(relative);
}

function writeRules(root: string, report: AdoptionReport): void {
  const path = join(root, 'AGENTS.md');
  const block = renderRules();
  const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
  const start = current.indexOf(rulesStart);
  const end = current.indexOf(rulesEnd);
  let next: string;
  if (start >= 0 && end > start)
    next = `${current.slice(0, start)}${block}${current.slice(end + rulesEnd.length).replace(/^\n/u, '')}`;
  else
    next =
      current === '' ? block : `${current.replace(/\n*$/u, '\n')}\n${block}`;
  if (next === current) report.unchanged.push('AGENTS.md');
  else {
    writeFileSync(path, next);
    report.written.push('AGENTS.md');
  }
  const link = join(root, 'CLAUDE.md');
  if (!existsSync(link) && !isSymlink(link)) {
    symlinkSync('AGENTS.md', link);
    report.written.push('CLAUDE.md');
  } else report.unchanged.push('CLAUDE.md');
}

function isSymlink(path: string): boolean {
  try {
    return lstatSync(path).isSymbolicLink();
  } catch {
    return false;
  }
}

function ignoreAgentState(root: string, report: AdoptionReport): void {
  const path = join(root, '.gitignore');
  const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
  if (current.split('\n').some((line) => line.trim() === '.krn/')) {
    report.unchanged.push('.gitignore');
    return;
  }
  appendFileSync(
    path,
    `${current === '' || current.endsWith('\n') ? '' : '\n'}.krn/\n`,
  );
  report.written.push('.gitignore');
}

function seedTasks(root: string, report: AdoptionReport): void {
  if (existsSync(join(root, 'tasks'))) {
    report.unchanged.push('tasks');
    return;
  }
  createTask(root, {
    title: 'Require the ci / Check status on the default branch',
    priority: 1,
    body: [
      'Outcome: merging to the default branch needs a green `ci / Check` and auto-merge is enabled.',
      'Why: the adopted delivery rules treat that Check as the only gate.',
      'Proof: a pull request with a red Check stays unmerged.',
    ],
  });
  report.written.push('tasks');
}

/** krn.json from detection (the operator may edit it); an existing file is never touched. */
function writeContract(
  root: string,
  options: AdoptOptions,
  report: AdoptionReport,
): void {
  if (existsSync(join(root, CONTRACT_FILE))) {
    report.unchanged.push(CONTRACT_FILE);
    return;
  }
  const found = findContract(root);
  const test = options.test ?? found?.contract.test;
  if (test === undefined) {
    report.skipped.push(
      `${CONTRACT_FILE} (no test command detected; pass --test CMD or write it)`,
    );
    return;
  }
  const { contract } = found ?? {};
  const body = {
    base: contract?.base ?? detectBase(root),
    test,
    ...(contract?.related && options.test === undefined
      ? { related: contract.related }
      : {}),
    ...(contract?.fast && options.test === undefined
      ? { fast: contract.fast }
      : {}),
    tracker: options.ref !== undefined || options.tracker ? 'krn' : 'none',
  };
  writeIfChanged(
    root,
    CONTRACT_FILE,
    `${JSON.stringify(body, null, 2)}\n`,
    report,
  );
}

const stopCommand = 'krn hook stop';

interface HookEntry {
  hooks?: { type?: string; command?: unknown }[];
}

/** Adds the Stop hook that calls `krn hook stop`, keeping every other setting and hook. */
function writeHooks(root: string, report: AdoptionReport): void {
  const relative = '.claude/settings.json';
  const path = join(root, relative);
  let settings: Record<string, unknown> = {};
  if (existsSync(path)) {
    try {
      const parsed: unknown = JSON.parse(readFileSync(path, 'utf8'));
      if (
        typeof parsed !== 'object' ||
        parsed === null ||
        Array.isArray(parsed)
      )
        throw new Error('expected an object');
      settings = parsed as Record<string, unknown>;
    } catch (error) {
      throw new Error(`${relative}: ${(error as Error).message}`);
    }
  }
  const hooks = (settings.hooks ?? {}) as Record<string, unknown>;
  const stop = Array.isArray(hooks.Stop) ? (hooks.Stop as HookEntry[]) : [];
  if (
    !stop.some((entry) =>
      entry.hooks?.some((hook) => hook.command === stopCommand),
    )
  )
    stop.push({ hooks: [{ type: 'command', command: stopCommand }] });
  settings.hooks = { ...hooks, Stop: stop };
  writeIfChanged(
    root,
    relative,
    `${JSON.stringify(settings, null, 2)}\n`,
    report,
  );
}

/** Writes the adoption set into `root`, a git repository; reruns change nothing. */
export function adopt(root: string, options: AdoptOptions): AdoptionReport {
  if (!existsSync(join(root, '.git')))
    throw new Error(`${root} is not a git repository root`);
  const report: AdoptionReport = { written: [], unchanged: [], skipped: [] };
  const workflow =
    options.ref === undefined
      ? undefined
      : renderWorkflow({ ...options, ref: options.ref });
  if (options.ref !== undefined || options.tracker) seedTasks(root, report);
  writeContract(root, options, report);
  writeHooks(root, report);
  writeRules(root, report);
  ignoreAgentState(root, report);
  const seeded = seedConventions(root, new Date().toISOString().slice(0, 10));
  if (seeded) report.written.push(seeded);
  else report.unchanged.push('conventions');
  if (workflow !== undefined)
    writeIfChanged(root, '.github/workflows/ci.yml', workflow, report);
  return report;
}
