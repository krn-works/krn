// The user-level standards file: the in-force universal records of the whole pack and the overlay
// (they hold in any repository and any stack): the top ones that fit the budget are rendered into one
// KRN-owned file that ~/.claude/CLAUDE.md imports, plus links to the universal project skills and the
// heavy-command PreToolUse hook in ~/.claude/settings.json and ~/.codex/hooks.json,
// plus the `heavy-gate` host entry in ~/.local/bin. KRN process (tracker, lanes, ship) never goes here.
import {
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  readlinkSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs';
import { join } from 'node:path';
import { instructionFile, userDir } from '../harness/claude.ts';
import { SUBJECT_MAX, TYPES } from '../repo/commit-title.ts';
import { contractConventions } from '../repo/contract.ts';
import { assertFormat } from '../repo/formats.ts';
import { parseUnified, type UnifiedRecord } from './record.ts';
import { StandardsDataError } from './standards.ts';

/** The generated file, relative to ~/.claude. */
export const GLOBAL_FILE = 'krn-standards.md';
/** The single line added to ~/.claude/CLAUDE.md. */
export const IMPORT_LINE = `@${GLOBAL_FILE}`;
/** Largest size of the generated file; every session on the host loads it. */
export const GLOBAL_BUDGET_BYTES = 2560;
/** Project skills (under .agents/skills) that hold in any stack. */
export const UNIVERSAL_SKILLS = ['architecture'] as const;

const PACK = 'standards/records.json';
/** The record the commit and PR convention below states in full, so it is not rendered twice. */
const CONVENTION_SUPERSEDES = 's-semantic-commits';

/**
 * The one commit, PR and merge convention of every repository, from the format owner
 * (src/repo/commit-title.ts); rendered first and never cut by the budget.
 */
export const COMMIT_CONVENTION = `- Commits and PRs: subject and PR title are \`type(scope): outcome\` (type ${TYPES.join('|')}); outcome states the observable behaviour after the change, starts lowercase, has no trailing period and at most ${SUBJECT_MAX} characters before a \`(t-id)\` or \`(#N)\` suffix. The PR title is the squash subject; the PR body has the sections Why, What changed, Verified (\`command: verdict\`) and Ticket/Refs when the repository tracks tasks (\`krn pr body\`). Merge by squash only (title PR_TITLE, body PR_BODY), delete the branch, auto-merge on the required check (\`krn repo settings\`).`;
const HEADER = `<!-- Generated by \`krn standards install --global\`; owned by KRN. Do not edit: rerun the command. -->`;
const TIER_RANK: Readonly<Record<string, number>> = {
  floor: 0,
  reflex: 1,
  finish: 2,
};

/**
 * The universal in-force records of a product checkout: its own overlay first (hand-curated),
 * then the pack by tier (floor, reflex, finish) and id, so the cut at the budget is deterministic.
 */
export function universalRecords(
  product: string,
  asOf: string,
): UnifiedRecord[] {
  assertFormat(product, 'krn.record');
  const overlay = parseUnified(
    JSON.parse(
      readFileSync(join(product, contractConventions(product)), 'utf8'),
    ),
  );
  const pack = parseUnified(
    JSON.parse(readFileSync(join(product, PACK), 'utf8')),
  );
  const inForce = (r: UnifiedRecord): boolean =>
    r.universal === true &&
    r.status !== 'retired' &&
    r.audience !== 'adopt' &&
    r.audience !== 'lead' &&
    r.valid_from <= asOf &&
    (r.valid_to === null || r.valid_to >= asOf);
  const rank = (a: UnifiedRecord, b: UnifiedRecord): number =>
    (TIER_RANK[a.tier] ?? 1) - (TIER_RANK[b.tier] ?? 1) ||
    a.id.localeCompare(b.id);
  const own = new Set(overlay.map((r) => r.id));
  return [
    ...overlay.filter(inForce),
    ...pack.filter((r) => inForce(r) && !own.has(r.id)).sort(rank),
  ];
}

/** The text of the generated file: the top universal records that fit the budget, in order. */
export function renderGlobalFile(product: string, asOf: string): string {
  const head = [
    HEADER,
    '# Engineering standards (any repository)',
    COMMIT_CONVENTION,
  ];
  const lines: string[] = [];
  const render = (): string => `${[...head, ...lines].join('\n')}\n`;
  for (const r of universalRecords(product, asOf)) {
    if (r.id === CONVENTION_SUPERSEDES) continue;
    lines.push(`- ${r.text}`);
    if (Buffer.byteLength(render()) > GLOBAL_BUDGET_BYTES) lines.pop();
  }
  return render();
}

function skillTarget(product: string, name: string): string {
  return join(product, '.agents', 'skills', name);
}

function readOr(path: string): string | null {
  return existsSync(path) ? readFileSync(path, 'utf8') : null;
}

function linkState(path: string, target: string): 'ok' | 'absent' | 'other' {
  let stat: ReturnType<typeof lstatSync>;
  try {
    stat = lstatSync(path);
  } catch {
    return 'absent';
  }
  return stat.isSymbolicLink() && readlinkSync(path) === target
    ? 'ok'
    : 'other';
}

/** The command of the user-scope heavy-command hook, which sends any repository's heavy jobs through the host gate; Codex gets the refusing form. */
export function heavyHookCommand(product: string, codex: boolean): string {
  return `node '${join(product, 'src', 'hook', 'heavy-command.ts')}'${codex ? ' --codex' : ''}`;
}

/** The host entry of the heavy-job gate, relative to the home directory. */
export const GATE_LINK = join('.local', 'bin', 'heavy-gate');

function gateTarget(product: string): string {
  return join(product, 'bin', 'heavy-gate');
}

type HookFile = { hooks?: Record<string, unknown> } & Record<string, unknown>;

/** The hook settings `text` with one PreToolUse Bash entry for `command` added, or null when it is already there. Every other entry stays. */
export function withCommitHook(
  text: string | null,
  command: string,
): string | null {
  const settings = (
    text === null || text.trim() === '' ? {} : JSON.parse(text)
  ) as HookFile;
  const hooks = settings.hooks ?? {};
  const pre = Array.isArray(hooks.PreToolUse) ? hooks.PreToolUse : [];
  const present = pre.some(
    (entry: { hooks?: Array<{ command?: unknown }> }) =>
      Array.isArray(entry?.hooks) &&
      entry.hooks.some((hook) => hook?.command === command),
  );
  if (present) return null;
  const entry = {
    matcher: 'Bash',
    hooks: [{ type: 'command', command, timeout: 5 }],
  };
  return `${JSON.stringify({ ...settings, hooks: { ...hooks, PreToolUse: [...pre, entry] } }, null, 2)}\n`;
}

/** The user-scope hook files and the PreToolUse Bash commands each one holds: Claude Code always, Codex when its home exists. */
function hookFiles(
  home: string,
  product: string,
): Array<{ file: string; commands: string[] }> {
  const codex = join(home, '.codex');
  const forHarness = (isCodex: boolean) => [heavyHookCommand(product, isCodex)];
  return [
    { file: join(userDir(home), 'settings.json'), commands: forHarness(false) },
    ...(existsSync(codex)
      ? [{ file: join(codex, 'hooks.json'), commands: forHarness(true) }]
      : []),
  ];
}

/** Names every difference between `home/.claude` and what the install writes; empty means no drift. */
export function globalDrift(
  home: string,
  product: string,
  asOf: string,
): string[] {
  const dir = userDir(home);
  const drift: string[] = [];
  if (readOr(join(dir, GLOBAL_FILE)) !== renderGlobalFile(product, asOf))
    drift.push(`${GLOBAL_FILE}: missing or differs from the generated text`);
  const lines = (readOr(join(dir, instructionFile)) ?? '').split('\n');
  if (!lines.includes(IMPORT_LINE))
    drift.push(`CLAUDE.md: lacks the line ${IMPORT_LINE}`);
  for (const name of UNIVERSAL_SKILLS)
    if (
      linkState(join(dir, 'skills', name), skillTarget(product, name)) !== 'ok'
    )
      drift.push(`skills/${name}: not a link to the KRN skill`);
  for (const { file, commands } of hookFiles(home, product))
    for (const command of commands)
      if (withCommitHook(readOr(file), command) !== null)
        drift.push(`${file}: lacks the PreToolUse hook ${command}`);
  if (linkState(join(home, GATE_LINK), gateTarget(product)) !== 'ok')
    drift.push(`${GATE_LINK}: not a link to the KRN heavy-job gate`);
  return drift;
}

/** Writes the generated file, the import line (only when absent) and the skill links; returns what changed. */
export function installGlobal(
  home: string,
  product: string,
  asOf: string,
): string[] {
  const dir = userDir(home);
  const text = renderGlobalFile(product, asOf);
  for (const name of UNIVERSAL_SKILLS)
    if (
      linkState(join(dir, 'skills', name), skillTarget(product, name)) ===
      'other'
    )
      throw new StandardsDataError(
        `${join(dir, 'skills', name)} exists and is not a link to the KRN skill; move it first`,
      );
  const gateLink = join(home, GATE_LINK);
  if (linkState(gateLink, gateTarget(product)) === 'other')
    throw new StandardsDataError(
      `${gateLink} exists and is not a link to the KRN heavy-job gate; move it first`,
    );
  mkdirSync(join(dir, 'skills'), { recursive: true });
  const changed: string[] = [];
  if (readOr(join(dir, GLOBAL_FILE)) !== text) {
    writeFileSync(join(dir, GLOBAL_FILE), text);
    changed.push(GLOBAL_FILE);
  }
  const claude = readOr(join(dir, instructionFile));
  if (!(claude ?? '').split('\n').includes(IMPORT_LINE)) {
    const prefix =
      claude === null || claude === ''
        ? ''
        : claude.endsWith('\n')
          ? `${claude}\n`
          : `${claude}\n\n`;
    writeFileSync(join(dir, instructionFile), `${prefix}${IMPORT_LINE}\n`);
    changed.push(instructionFile);
  }
  for (const name of UNIVERSAL_SKILLS) {
    const link = join(dir, 'skills', name);
    if (linkState(link, skillTarget(product, name)) === 'absent') {
      symlinkSync(skillTarget(product, name), link);
      changed.push(`skills/${name}`);
    }
  }
  for (const { file, commands } of hookFiles(home, product)) {
    let text = readOr(file);
    for (const command of commands)
      text = withCommitHook(text, command) ?? text;
    if (text === readOr(file) || text === null) continue;
    writeFileSync(file, text);
    changed.push(file);
  }
  if (linkState(gateLink, gateTarget(product)) === 'absent') {
    mkdirSync(join(home, '.local', 'bin'), { recursive: true });
    symlinkSync(gateTarget(product), gateLink);
    changed.push(GATE_LINK);
  }
  return changed;
}
