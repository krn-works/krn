import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import {
  lstatSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readlinkSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import {
  GLOBAL_BUDGET_BYTES,
  GLOBAL_FILE,
  IMPORT_LINE,
} from '../../src/brain/global-standards.ts';
import { parseRecords } from '../../src/brain/packet.ts';

const product = fileURLToPath(new URL('../..', import.meta.url));
const krn = join(product, 'bin', 'krn');

function run(home: string, ...args: string[]) {
  return spawnSync(krn, ['standards', 'install', '--global', ...args], {
    encoding: 'utf8',
    env: { ...process.env, HOME: home },
  });
}

function freshHome(): string {
  const base = process.env.TMPDIR ?? tmpdir();
  const home = mkdtempSync(join(base, 'krn-global-'));
  mkdirSync(join(home, '.claude'));
  return home;
}

const records = parseRecords(
  JSON.parse(readFileSync(join(product, '.agents/conventions.json'), 'utf8')),
);

test('the file holds exactly the universal in-force records within the budget', () => {
  const home = freshHome();
  assert.equal(run(home).status, 0);
  const text = readFileSync(join(home, '.claude', GLOBAL_FILE), 'utf8');
  const universal = records.filter(
    (r) => r.universal === true && r.valid_to === null,
  );
  assert.ok(universal.length > 0);
  for (const r of universal) assert.ok(text.includes(`- ${r.text}`), r.id);
  assert.equal(
    text.split('\n').filter((l) => l.startsWith('- ')).length,
    universal.length,
  );
  assert.ok(Buffer.byteLength(text) <= GLOBAL_BUDGET_BYTES);
  assert.match(text, /Generated by `krn standards install --global`/u);
});

test('no process or repository-specific record reaches the file', () => {
  const home = freshHome();
  run(home);
  const text = readFileSync(join(home, '.claude', GLOBAL_FILE), 'utf8');
  for (const r of records.filter((x) => x.universal !== true))
    assert.ok(!text.includes(r.text), r.id);
  assert.doesNotMatch(text, /krn task|tracker|\.krn\/|shard-weights|biome/iu);
});

test('the import line and skill links are added, other CLAUDE.md content is kept', () => {
  const home = freshHome();
  const own = '# Mine\n\n- keep this\n';
  writeFileSync(join(home, '.claude', 'CLAUDE.md'), own);
  run(home);
  assert.equal(
    readFileSync(join(home, '.claude', 'CLAUDE.md'), 'utf8'),
    `${own}\n${IMPORT_LINE}\n`,
  );
  for (const name of ['architecture', 'typescript']) {
    const link = join(home, '.claude', 'skills', name);
    assert.ok(lstatSync(link).isSymbolicLink());
    assert.equal(readlinkSync(link), join(product, '.agents', 'skills', name));
  }
});

test('a rerun changes nothing', () => {
  const home = freshHome();
  run(home);
  const before = readFileSync(join(home, '.claude', 'CLAUDE.md'), 'utf8');
  const again = run(home);
  assert.equal(again.status, 0);
  assert.match(again.stdout, /unchanged/u);
  assert.equal(
    readFileSync(join(home, '.claude', 'CLAUDE.md'), 'utf8'),
    before,
  );
});

test('--check passes after install and fails after a manual edit', () => {
  const home = freshHome();
  assert.equal(run(home, '--check').status, 1);
  run(home);
  assert.equal(run(home, '--check').status, 0);
  writeFileSync(join(home, '.claude', GLOBAL_FILE), 'edited\n');
  const drift = run(home, '--check');
  assert.equal(drift.status, 1);
  assert.match(drift.stderr, new RegExp(GLOBAL_FILE, 'u'));
});

test('a record with a non-true universal field is rejected', () => {
  const [one] = records;
  assert.throws(
    () => parseRecords([{ ...one, universal: false }]),
    /universal/u,
  );
});
