import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import {
  lstatSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readlinkSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import {
  COMMIT_CONVENTION,
  GATE_LINK,
  GLOBAL_BUDGET_BYTES,
  GLOBAL_FILE,
  heavyHookCommand,
  IMPORT_LINE,
} from '../../src/brain/global-standards.ts';
import { parseRecords } from '../../src/brain/packet.ts';

const product = fileURLToPath(new URL('../..', import.meta.url));
const krn = join(product, 'bin', 'krn');

function run(home: string, ...args: string[]) {
  return spawnSync(krn, ['standards', 'install', '--global', ...args], {
    encoding: 'utf8',
    env: { ...process.env, HOME: home },
  });
}

function freshHome(): string {
  const base = process.env.TMPDIR ?? tmpdir();
  const home = mkdtempSync(join(base, 'krn-global-'));
  mkdirSync(join(home, '.claude'));
  return home;
}

const records = parseRecords(
  JSON.parse(readFileSync(join(product, '.agents/records.json'), 'utf8')),
);

test('the file renders the top universal records of the whole pack within the budget', () => {
  const home = freshHome();
  assert.equal(run(home).status, 0);
  const text = readFileSync(join(home, '.claude', GLOBAL_FILE), 'utf8');
  const universal = records.filter(
    (r) => r.universal === true && r.valid_to === null,
  );
  assert.ok(universal.length > 0);
  // The overlay's own universal records come first and all fit.
  for (const r of universal) assert.ok(text.includes(`- ${r.text}`), r.id);
  const lines = text.split('\n').filter((l) => l.startsWith('- '));
  assert.ok(lines.length > 4, `${lines.length} records`);
  assert.ok(lines.length > universal.length, 'pack records are rendered too');
  assert.ok(Buffer.byteLength(text) <= GLOBAL_BUDGET_BYTES);
  assert.match(text, /Generated by `krn standards install --global`/u);
});

test('no process or repository-specific record reaches the file', () => {
  const home = freshHome();
  run(home);
  const text = readFileSync(join(home, '.claude', GLOBAL_FILE), 'utf8');
  for (const r of records.filter((x) => x.universal !== true))
    assert.ok(!text.includes(r.text), r.id);
  assert.doesNotMatch(text, /krn task|tracker|\.krn\/|shard-weights|biome/iu);
});

test('the import line and skill links are added, other CLAUDE.md content is kept', () => {
  const home = freshHome();
  const own = '# Mine\n\n- keep this\n';
  writeFileSync(join(home, '.claude', 'CLAUDE.md'), own);
  run(home);
  assert.equal(
    readFileSync(join(home, '.claude', 'CLAUDE.md'), 'utf8'),
    `${own}\n${IMPORT_LINE}\n`,
  );
  for (const name of ['architecture']) {
    const link = join(home, '.claude', 'skills', name);
    assert.ok(lstatSync(link).isSymbolicLink());
    assert.equal(readlinkSync(link), join(product, '.agents', 'skills', name));
  }
});

test('a rerun changes nothing', () => {
  const home = freshHome();
  run(home);
  const before = readFileSync(join(home, '.claude', 'CLAUDE.md'), 'utf8');
  const again = run(home);
  assert.equal(again.status, 0);
  assert.match(again.stdout, /unchanged/u);
  assert.equal(
    readFileSync(join(home, '.claude', 'CLAUDE.md'), 'utf8'),
    before,
  );
});

test('--check passes after install and fails after a manual edit', () => {
  const home = freshHome();
  assert.equal(run(home, '--check').status, 1);
  run(home);
  assert.equal(run(home, '--check').status, 0);
  writeFileSync(join(home, '.claude', GLOBAL_FILE), 'edited\n');
  const drift = run(home, '--check');
  assert.equal(drift.status, 1);
  assert.match(drift.stderr, new RegExp(GLOBAL_FILE, 'u'));
});

test('a record with a non-true universal field is rejected', () => {
  const [one] = records;
  assert.throws(
    () => parseRecords([{ ...one, universal: false }]),
    /universal/u,
  );
});

test('the file states the commit, PR and merge convention once', () => {
  const home = freshHome();
  run(home);
  const text = readFileSync(join(home, '.claude', GLOBAL_FILE), 'utf8');
  assert.ok(text.includes(COMMIT_CONVENTION));
  assert.match(text, /PR_TITLE, body PR_BODY/u);
  assert.match(text, /at most 100 characters/u);
  assert.doesNotMatch(text, /Commit subjects since the repository adopted/u);
});

test('the heavy-command hook joins the user Claude and Codex hooks, other entries kept', () => {
  const home = freshHome();
  mkdirSync(join(home, '.codex'));
  const other = {
    model: 'x',
    hooks: {
      PreToolUse: [
        { matcher: 'Bash', hooks: [{ type: 'command', command: 'mine' }] },
      ],
      Stop: [{ hooks: [{ type: 'command', command: 'stop-mine' }] }],
    },
  };
  writeFileSync(
    join(home, '.claude', 'settings.json'),
    JSON.stringify(other, null, 2),
  );
  assert.equal(run(home).status, 0);
  for (const [file, codex] of [
    [join(home, '.claude', 'settings.json'), false],
    [join(home, '.codex', 'hooks.json'), true],
  ] as const) {
    const settings = JSON.parse(readFileSync(file, 'utf8'));
    const commands = settings.hooks.PreToolUse.flatMap(
      (entry: { hooks: Array<{ command: string }> }) =>
        entry.hooks.map((hook) => hook.command),
    );
    assert.ok(commands.includes(heavyHookCommand(product, codex)), file);
    assert.ok(!commands.includes(heavyHookCommand(product, !codex)), file);
  }
  const claude = JSON.parse(
    readFileSync(join(home, '.claude', 'settings.json'), 'utf8'),
  );
  assert.equal(claude.model, 'x');
  assert.equal(claude.hooks.PreToolUse[0].hooks[0].command, 'mine');
  assert.equal(claude.hooks.Stop[0].hooks[0].command, 'stop-mine');
  assert.equal(claude.hooks.PreToolUse.length, 2);
  assert.equal(run(home, '--check').status, 0);
  run(home);
  assert.equal(
    JSON.parse(readFileSync(join(home, '.claude', 'settings.json'), 'utf8'))
      .hooks.PreToolUse.length,
    2,
  );
});

test('the heavy-gate host entry links the gate and runs it', () => {
  const home = freshHome();
  assert.equal(run(home).status, 0);
  const link = join(home, GATE_LINK);
  assert.equal(readlinkSync(link), join(product, 'bin', 'heavy-gate'));
  const ran = spawnSync(link, ['run', '--', 'sh', '-c', 'exit 7'], {
    encoding: 'utf8',
    env: {
      ...process.env,
      KRN_HEAVY_GATE_DIR: join(home, 'gate'),
      KRN_TEST_SLOT_HELD: '',
    },
  });
  assert.equal(ran.status, 7, ran.stderr);
  rmSync(link);
  writeFileSync(link, 'mine');
  const check = run(home, '--check');
  assert.equal(check.status, 1);
  assert.match(check.stderr, /heavy-gate: not a link/u);
  assert.equal(run(home).status, 65);
});
