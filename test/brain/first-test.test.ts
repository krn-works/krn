import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { goToolchainBin } from '../../scripts/outside-acceptance.ts';
import {
  type FirstTestStack,
  firstTestRecipe,
  firstTestStack,
} from '../../src/brain/first-test.ts';
import { laneBriefText } from '../../src/cli/lane-brief.ts';
import {
  bootstrapProof,
  mutationCandidates,
} from '../../src/cli/lane-run/bootstrap.ts';

function fixture(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), 'first-test-'));
  for (const [name, text] of Object.entries(files)) {
    mkdirSync(join(root, name, '..'), { recursive: true });
    writeFileSync(join(root, name), text);
  }
  const git = (...args: string[]) =>
    spawnSync('git', ['-C', root, ...args], { encoding: 'utf8' });
  git('init', '-q');
  git('add', '-A');
  git('-c', 'user.name=t', '-c', 'user.email=t@t', 'commit', '-qm', 'x');
  return root;
}

const vacuous = JSON.stringify({ test: 'exit 1', vacuous: true });
const PHP = '<?php\nfunction add($a, $b) {\n    return $a + $b;\n}\n';
const JS = 'export const add = (a, b) => {\n  return a + b;\n};\n';

const cases: Array<{
  stack: FirstTestStack;
  files: Record<string, string>;
  tests: Record<string, string>;
  command: string;
}> = [
  {
    stack: 'php',
    files: { 'krn.json': vacuous, 'composer.json': '{}', 'lib.php': PHP },
    tests: {
      'tests/smoke.php':
        "<?php\nrequire __DIR__ . '/../lib.php';\nexit(add(2, 3) === 5 ? 0 : 1);\n",
    },
    command: 'php tests/smoke.php',
  },
  {
    stack: 'wordpress',
    files: { 'krn.json': vacuous, 'functions.php': PHP, 'style.css': '/**/' },
    tests: {
      'tests/smoke.php':
        "<?php\nrequire __DIR__ . '/../functions.php';\nexit(add(2, 3) === 5 ? 0 : 1);\n",
    },
    command: 'php tests/smoke.php',
  },
  {
    stack: 'rust',
    files: {
      'krn.json': vacuous,
      'Cargo.toml':
        '[package]\nname = "probe"\nversion = "0.1.0"\nedition = "2021"\n',
      'Cargo.lock':
        '# This file is automatically @generated by Cargo.\nversion = 3\n\n[[package]]\nname = "probe"\nversion = "0.1.0"\n',
      'src/lib.rs':
        'pub fn add(a: i32, b: i32) -> i32 {\n    return a + b;\n}\n',
    },
    tests: {
      'tests/add.rs':
        'use probe::add;\n\n#[test]\nfn adds() {\n    assert_eq!(add(2, 3), 5);\n}\n',
    },
    command: 'cargo test --offline',
  },
  {
    stack: 'npm',
    files: { 'krn.json': vacuous, 'package.json': '{}', 'lib.mjs': JS },
    tests: {
      'test/lib.test.mjs':
        'import test from "node:test";\nimport assert from "node:assert/strict";\nimport { add } from "../lib.mjs";\ntest("add", () => assert.equal(add(2, 3), 5));\n',
    },
    command: 'node --test',
  },
];

const cargoRuns =
  spawnSync('cargo', ['--version'], { encoding: 'utf8' }).status === 0;

for (const c of cases) {
  test(`the ${c.stack} recipe names its stack and its fixture goes from vacuous to red-on-mutation`, () => {
    const root = fixture(c.files);
    try {
      assert.equal(firstTestStack(root), c.stack);
      assert.match(
        laneBriefText(root, 'brief', '2026-11-14'),
        /First-test recipe/u,
      );
      assert.match(firstTestRecipe(c.stack), /krn\.json "test"/u);
      // Without a usable cargo the stack and recipe checks above are all this host can prove.
      if (c.stack === 'rust' && !cargoRuns) return;
      for (const [name, text] of Object.entries(c.tests)) {
        mkdirSync(join(root, name, '..'), { recursive: true });
        writeFileSync(join(root, name), text);
      }
      writeFileSync(
        join(root, 'krn.json'),
        JSON.stringify({ test: c.command }),
      );
      spawnSync('git', ['-C', root, 'add', '-A']);
      // a nested node --test run inside this runner would report green as a subtest
      delete process.env.NODE_TEST_CONTEXT;
      const proof = bootstrapProof(root, c.command);
      assert.ok('verified' in proof, JSON.stringify(proof));
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
}

test('a static site gets the node:test recipe and a non-vacuous repository gets no recipe', () => {
  const root = fixture({ 'krn.json': '{"test":"true"}', 'index.html': '<p>' });
  try {
    assert.equal(firstTestStack(root), 'static');
    assert.doesNotMatch(
      laneBriefText(root, 'brief', '2026-11-14'),
      /First-test recipe/u,
    );
    assert.match(firstTestRecipe('static'), /node:test/u);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('a TypeScript npm repository with a declared runner gets the runner and the .js-import trap in its recipe', () => {
  const root = fixture({
    'krn.json': vacuous,
    'tsconfig.json': '{}',
    'package.json': JSON.stringify({ devDependencies: { vitest: '^4' } }),
    'src/index.ts': 'export { add } from "./add.js";\n',
    'src/add.ts': 'export const add = (a: number, b: number) => a + b;\n',
  });
  try {
    const brief = laneBriefText(root, 'brief', '2026-11-14');
    assert.match(brief, /First-test recipe \(npm\)/u);
    assert.match(brief, /ERR_MODULE_NOT_FOUND/u);
    assert.match(brief, /npx vitest run <that test file>/u);
    assert.match(brief, /Never assert only on data, config or docs files/u);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('a plain JavaScript npm repository gets no TypeScript or runner hint', () => {
  const root = fixture({
    'krn.json': vacuous,
    'package.json': '{"name":"x"}',
    'add.mjs': JS,
  });
  try {
    const brief = laneBriefText(root, 'brief', '2026-11-14');
    assert.match(brief, /First-test recipe \(npm\)/u);
    assert.doesNotMatch(
      brief,
      /ERR_MODULE_NOT_FOUND|declares (vitest|jest|mocha)/u,
    );
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('mutation candidates start with the sources the selected tests import, .js specifiers resolved to .ts', () => {
  const texts: Record<string, string> = {
    'test/scan.test.mjs': 'import { scanAll } from "../src/ledger/scan.ts";\n',
    'src/ledger/scan.ts':
      'import type { Row } from "./types.js";\nimport { sum } from "./sum.js";\n',
    'src/ledger/sum.ts': 'export const sum = 1;\n',
    'src/ledger/types.ts': 'export type Row = number;\n',
    'test/ledger/other.test.ts':
      'import { x } from "../../src/adapters/a.ts";\n',
  };
  const tracked = [
    'scripts/demo.ts',
    'src/adapters/a.ts',
    ...Object.keys(texts),
  ].sort();
  const read = (file: string) => texts[file] ?? '';
  const candidates = mutationCandidates(
    read,
    'node --test test/*.test.mjs',
    tracked,
  );
  assert.deepEqual(candidates.slice(0, 3), [
    'src/ledger/scan.ts',
    'src/ledger/types.ts',
    'src/ledger/sum.ts',
  ]);
  assert.ok(candidates.includes('scripts/demo.ts'));
  assert.ok(!candidates.some((file) => file.startsWith('test/')));
});

test('the bootstrap proof mutates the module the new test imports even when a dozen sources sort before it', () => {
  const filler: Record<string, string> = {};
  for (let index = 0; index < 14; index++)
    filler[`src/a${String(index).padStart(2, '0')}.mjs`] =
      'export const unused = () => {\n  return console.log("x");\n};\n';
  const root = fixture({
    ...filler,
    'package.json': '{"name":"x","type":"module"}',
    'src/z/add.mjs': JS,
    'test/add.test.mjs':
      'import test from "node:test";\nimport assert from "node:assert/strict";\nimport { add } from "../src/z/add.mjs";\ntest("add", () => assert.equal(add(2, 3), 5));\n',
    'krn.json': JSON.stringify({ test: 'node --test test/*.test.mjs' }),
  });
  try {
    delete process.env.NODE_TEST_CONTEXT;
    const proof = bootstrapProof(root, 'node --test test/*.test.mjs');
    assert.ok('verified' in proof, JSON.stringify(proof));
    assert.match(proof.verified, /src\/z\/add\.mjs/u);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('clause 6: a Go module gets the Go recipe, and the test command a first Go test names is red on mutation', () => {
  const root = fixture({
    'krn.json': vacuous,
    'go.mod': 'module probe\n\ngo 1.21\n',
    'add.go': 'package probe\n\nfunc Add(a, b int) int {\n\treturn a + b\n}\n',
  });
  try {
    assert.equal(firstTestStack(root), 'go');
    assert.match(
      laneBriefText(root, 'brief', '2026-11-14'),
      /First-test recipe \(go\).*go test \.\/\.\.\./u,
    );
    assert.match(firstTestRecipe('go'), /krn\.json "test"/u);
    const bin = goToolchainBin(
      join(process.env.HOME ?? '', '.local/share/mise/installs'),
    );
    if (bin === undefined) return;
    writeFileSync(
      join(root, 'add_test.go'),
      'package probe\n\nimport "testing"\n\nfunc TestAdd(t *testing.T) {\n\tif Add(2, 3) != 5 {\n\t\tt.Fatal("add")\n\t}\n}\n',
    );
    writeFileSync(
      join(root, 'krn.json'),
      JSON.stringify({ test: 'go test ./...' }),
    );
    spawnSync('git', ['-C', root, 'add', '-A']);
    delete process.env.NODE_TEST_CONTEXT;
    const path = process.env.PATH;
    process.env.PATH = `${bin}:${path}`;
    try {
      const proof = bootstrapProof(root, 'go test ./...');
      assert.ok('verified' in proof, JSON.stringify(proof));
    } finally {
      process.env.PATH = path;
    }
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('a Python repository is detected by its marker files and gets a pytest recipe', () => {
  for (const marker of ['pyproject.toml', 'requirements.txt', 'setup.py']) {
    const root = fixture({ [marker]: '' });
    try {
      assert.equal(firstTestStack(root), 'python', marker);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  }
  assert.match(firstTestRecipe('python'), /pytest/u);
});
