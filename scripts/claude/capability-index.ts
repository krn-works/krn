// KRN's own capability index: one line per src module from its header comment, plus the krn
// command table. SessionStart injects it; fast regenerates it; a test checks it is fresh.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { commandLines } from '../../src/cli/help.ts';
import { cutText } from './cut-text.ts';

export const indexPath = 'docs/generated/capability-index.md';

const lineLimit = 120;

function sources(directory: string): string[] {
  return readdirSync(directory, { withFileTypes: true })
    .flatMap((entry) => {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) return sources(path);
      return entry.isFile() && entry.name.endsWith('.ts') ? [path] : [];
    })
    .sort();
}

/** The leading comment block of a module (`//` lines or one block comment), joined on one line. */
export function moduleHeader(source: string): string | undefined {
  const lines = source
    .replace(/^#!.*\n/u, '')
    .split('\n')
    .map((line) => line.trim());
  const header: string[] = [];
  if (lines[0]?.startsWith('/*')) {
    for (const line of lines) {
      header.push(line.replace(/^\/\*+\s?|\s?\*+\/$|^\*\s?/gu, ''));
      if (line.includes('*/')) break;
    }
  } else {
    for (const line of lines) {
      if (!line.startsWith('//')) break;
      header.push(line.replace(/^\/\/\s?/u, ''));
    }
  }
  const text = header.join(' ').replace(/\s+/gu, ' ').trim();
  return text || undefined;
}

function exportsOf(source: string): string {
  const names = [
    ...source.matchAll(
      /^export\s+(?:async\s+)?(?:function|const|class|type|interface)\s+(\w+)/gmu,
    ),
  ].map((match) => match[1]);
  return names.length > 0
    ? `(no header) exports ${names.slice(0, 4).join(', ')}`
    : '(no header)';
}

/** The index text for a repository root. */
export function buildIndex(root: string): string {
  const modules = sources(join(root, 'src')).map((path) => {
    const source = readFileSync(path, 'utf8');
    const name = relative(root, path).split('\\').join('/');
    return cutText(
      `${name}: ${moduleHeader(source) ?? exportsOf(source)}`,
      lineLimit,
    );
  });
  const commands = commandLines().map((line) => {
    const [head = '', ...rest] = line.split('  ');
    return cutText(`${head.trim()}: ${rest.join(' ').trim()}`, lineLimit);
  });
  return `${[
    '# KRN capability index (generated by scripts/claude/capability-index.ts; fast rewrites it)',
    'Before calling anything foreign, unknown or missing, grep this index and src.',
    '',
    '## krn commands',
    ...commands,
    '',
    '## src modules',
    ...modules,
  ].join('\n')}\n`;
}

/** The committed index as a SessionStart block, bounded to the hook's context budget. */
export function indexBlock(root: string, limit = 9500): string | undefined {
  try {
    return cutText(readFileSync(join(root, indexPath), 'utf8'), limit);
  } catch {
    return undefined; // A missing index never interrupts startup.
  }
}

/** Rewrites the committed index when it differs; true when it changed. */
export function writeIndex(root: string): boolean {
  const next = buildIndex(root);
  try {
    if (readFileSync(join(root, indexPath), 'utf8') === next) return false;
  } catch {
    /* A missing index is written below. */
  }
  writeFileSync(join(root, indexPath), next);
  return true;
}

if (import.meta.main) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
  if (process.argv.includes('--write')) {
    writeIndex(root);
  } else {
    const project = process.env.CLAUDE_PROJECT_DIR;
    const block = project ? indexBlock(project) : undefined;
    if (block)
      process.stdout.write(
        JSON.stringify({
          hookSpecificOutput: {
            hookEventName: 'SessionStart',
            additionalContext: block,
          },
        }),
      );
  }
}
