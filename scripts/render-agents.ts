// Render the checked-in repository instructions from their sole rule registry. ADR 0001.
import { readdir, readFile, writeFile } from 'node:fs/promises';

export type Rule = {
  id: string;
  trigger: string;
  action: string;
  owner: string;
  /** `lead`: governance and process rules a worker session never sees. */
  audience?: 'lead';
  enforcement: {
    kind: 'test' | 'gate' | 'none';
    check: string;
    deadline?: string;
  };
  rationale: string;
};

const root = new URL('../', import.meta.url);
const registryPath = new URL('spec/rules.json', root);
const agentsPath = new URL('AGENTS.md', root);
const { rules } = JSON.parse(await readFile(registryPath, 'utf8')) as {
  rules: Rule[];
};

function renderRule(rule: Rule): string {
  return `- **${rule.id}** When ${rule.trigger}, ${rule.action} _(owner: ${rule.owner}; ${rule.enforcement.kind}: ${rule.enforcement.check}; ${rule.rationale})_`;
}

/** The rules a worker session sees: scope prohibitions stay, lead and governance rules go. */
export function workerRules(all: readonly Rule[]): Rule[] {
  return all.filter((rule) => rule.audience !== 'lead');
}

/** `worker` omits the lead's workflow paragraph: it is a positive process directive. */
export function render(
  selected: readonly Rule[] = rules,
  worker = false,
): string {
  return [
    '<!-- Generated by scripts/render-agents.ts from spec/rules.json. -->',
    '<!-- krn-agent-workflow:start -->',
    '# KRN repository rules',
    '',
    ...(worker
      ? []
      : [
          'This file is already loaded as CLAUDE.md; do not read it again. Small change: edit, run `npm run fast` once (biome --write, tsc, related tests, one verdict), commit; CI runs the rest.',
          '',
        ]),
    ...selected.map(renderRule),
    '<!-- krn-agent-workflow:end -->',
    '',
  ].join('\n');
}

async function checkRegistry(): Promise<string[]> {
  const { scripts } = JSON.parse(
    await readFile(new URL('package.json', root), 'utf8'),
  ) as { scripts: Record<string, string> };
  const testFiles = await readdir(new URL('test/', root), { recursive: true });
  const testSources = await Promise.all(
    testFiles
      .filter((file) => /\.test\.[cm]?[jt]s$/u.test(file))
      .map((file) => readFile(new URL(`test/${file}`, root), 'utf8')),
  );
  const titles = new Set(
    testSources.flatMap((source) =>
      [...source.matchAll(/\btest\(\s*['"]([^'"]+)['"]/gu)].map(
        (match) => match[1],
      ),
    ),
  );
  const errors: string[] = [];
  for (const rule of rules) {
    const { kind, check } = rule.enforcement;
    if (kind === 'test' && !titles.has(check))
      errors.push(`${rule.id} names missing test: ${check}`);
    if (
      kind === 'gate' &&
      !Object.hasOwn(scripts, check.replace(/^npm run /u, ''))
    )
      errors.push(`${rule.id} names missing gate script: ${check}`);
    if (kind === 'none' && rule.enforcement.deadline === undefined)
      errors.push(`${rule.id} none enforcement needs a migration deadline`);
  }
  return errors;
}

if (import.meta.main) {
  const expected = render();
  const checkOnly = process.argv.includes('--check');
  const write = process.argv.includes('--write');
  if (checkOnly === write) {
    process.stderr.write('Choose exactly one of --check or --write.\n');
    process.exitCode = 2;
  } else {
    const errors = await checkRegistry();
    if (errors.length) {
      process.stderr.write(`${errors.join('\n')}\n`);
      process.exitCode = 1;
    } else if (checkOnly) {
      const actual = await readFile(agentsPath, 'utf8').catch(() => '');
      if (actual !== expected) {
        process.stderr.write(
          'AGENTS.md is stale; run npm run render:agents.\n',
        );
        process.exitCode = 1;
      }
    } else {
      await writeFile(agentsPath, expected);
    }
  }
}
