// Adoption census: copies real operator repositories into scratch clones, runs the adoption surface of
// the CLI on each and renders one committed table. Usage: KRN_CENSUS_CODING=<dir> TMPDIR=<disk dir> node scripts/adoption-census.ts [--write]
// Repository contents are data: only the clone is touched, the origin remote is only read by `adopt --verify`.
import { spawnSync } from 'node:child_process';
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..');
const CODING = process.env.KRN_CENSUS_CODING ?? '';
const SCRATCH = join(tmpdir(), 'krn-adoption-census');
const TABLE = join(repoRoot, 'evals/adoption-census.md');

/** The census population: operator git repositories of mixed stacks, fixed so a rerun measures the same set. */
export const POPULATION: readonly string[] = [
  'rekurencja.com/Swieta-na-starowce',
  'krn/active/3d-wkladki',
  'krn/active/krn-zakupy',
  'krn/active/boilerplate-2026',
  'krn/active/perfect-memory',
  'krn/active/mise-en-plesk',
  'krn/active/ekologus-wp-local',
  'rekurencja.com/boilerplate-rekurencja',
  'rekurencja.com/ekologus-2025',
  'rekurencja.com/hasmed-2025',
  'rekurencja.com/lsn2-map',
  'rekurencja.com/limak',
  'rekurencja.com/dentalcity',
  'wycena-master',
  'vibe-coding/ekologus-core',
];

export function detectStack(
  files: readonly string[],
  packageJson?: string,
): string {
  const has = (name: string) => files.includes(name);
  const stacks: string[] = [];
  if (has('package.json')) {
    let workspaces = false;
    try {
      workspaces = 'workspaces' in JSON.parse(packageJson ?? '{}');
    } catch {
      // a malformed package.json is still an npm project
    }
    stacks.push(
      workspaces ? 'npm workspaces' : has('tsconfig.json') ? 'ts' : 'npm',
    );
  }
  if (has('composer.json') || files.some((f) => f.endsWith('.php')))
    stacks.push(
      has('wp-content') ||
        has('wp-config.php') ||
        has('functions.php') ||
        has('wp-cli.yml')
        ? 'php/wordpress'
        : 'php',
    );
  if (
    has('pyproject.toml') ||
    has('requirements.txt') ||
    has('requirements-tests.txt') ||
    (has('Makefile') && files.some((f) => f.endsWith('.py')))
  )
    stacks.push('python');
  return stacks.length > 0 ? stacks.join('+') : 'static/other';
}

export interface Row {
  repo: string;
  head: string;
  stack: string;
  adopt: number;
  standards: number;
  verify: number;
  test: string;
  gaps: string;
}

const cell = (text: string) =>
  text.replaceAll('|', '/').replaceAll('\n', ' ').trim();

export function renderTable(rows: readonly Row[]): string {
  const lines = [
    '# Adoption census',
    '',
    'Generated by `KRN_CENSUS_CODING=<dir> node scripts/adoption-census.ts --write`: scratch clones (`git clone --local --no-hardlinks` of each HEAD) of operator repositories, `krn adopt <clone>`, `krn standards check --root <clone>` and `krn adopt <clone> --verify`, with the clone origin set to the original origin so `--verify` reads the real GitHub repository. No push, originals untouched.',
    '',
    '| repo | HEAD | stack | adopt | standards check | verify | test command detected | gaps |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
  ];
  for (const r of rows)
    lines.push(
      `| ${cell(r.repo)} | ${r.head} | ${cell(r.stack)} | ${r.adopt} | ${r.standards} | ${r.verify} | ${cell(r.test)} | ${cell(r.gaps)} |`,
    );
  return `${lines.join('\n')}\n`;
}

function run(cmd: string, args: string[], cwd: string, timeout = 300_000) {
  const r = spawnSync(cmd, args, { cwd, encoding: 'utf8', timeout });
  return { status: r.status ?? 124, out: `${r.stdout ?? ''}${r.stderr ?? ''}` };
}

function lastLine(text: string): string {
  const lines = text.split('\n').filter((l) => l.trim() !== '');
  return lines.at(-1) ?? '';
}

function brief(text: string, max: number): string {
  return text.length > max ? `${text.slice(0, max)}...` : text;
}

function census(repo: string): Row {
  const source = join(CODING, repo);
  const clone = join(SCRATCH, repo.replaceAll('/', '__'));
  rmSync(clone, { recursive: true, force: true });
  const cloned = run(
    'git',
    ['clone', '-q', '--local', '--no-hardlinks', source, clone],
    SCRATCH,
  );
  if (cloned.status !== 0)
    return {
      repo,
      head: '-',
      stack: '-',
      adopt: cloned.status,
      standards: -1,
      verify: -1,
      test: '-',
      gaps: `clone failed: ${lastLine(cloned.out)}`,
    };
  const origin = run(
    'git',
    ['-C', source, 'remote', 'get-url', 'origin'],
    SCRATCH,
  );
  if (origin.status === 0)
    run(
      'git',
      ['-C', clone, 'remote', 'set-url', 'origin', origin.out.trim()],
      SCRATCH,
    );
  const head = run(
    'git',
    ['-C', clone, 'rev-parse', '--short', 'HEAD'],
    SCRATCH,
  ).out.trim();
  const files = readdirSync(clone);
  const pkg = existsSync(join(clone, 'package.json'))
    ? readFileSync(join(clone, 'package.json'), 'utf8')
    : undefined;
  const stack = detectStack(files, pkg);
  const krn = join(repoRoot, 'bin/krn');
  // adopt bounds its own canary (exit 124 after 180s); the census limit only catches a hang beyond it.
  const adopt = run(krn, ['adopt', clone], clone, 420_000);
  const standards = run(krn, ['standards', 'check', '--root', clone], clone);
  const verify = run(krn, ['adopt', clone, '--verify'], clone);
  let test = 'none';
  try {
    const contract = JSON.parse(
      readFileSync(join(clone, 'krn.json'), 'utf8'),
    ) as { test?: string };
    test = contract.test ?? 'none';
  } catch {
    // adopt writes no krn.json when it detects no test command
  }
  const gaps = [
    adopt.status === 0
      ? ''
      : adopt.status === 124 && !adopt.out.includes('canary timeout')
        ? 'adopt: killed by the census after 420s'
        : `adopt: ${brief(adopt.out.split('\n').find((l) => l.includes('failed')) ?? lastLine(adopt.out), 130)}`,
    standards.status === 0
      ? ''
      : `standards: ${[...new Set([...standards.out.matchAll(/\b(s-[a-z0-9-]+)/g)].map((m) => m[1]))].join(' ')}`,
    verify.status === 0 ? '' : `verify: ${brief(lastLine(verify.out), 70)}`,
  ]
    .filter(Boolean)
    .join('; ');
  return {
    repo,
    head,
    stack,
    adopt: adopt.status,
    standards: standards.status,
    verify: verify.status,
    test,
    gaps,
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (CODING === '') {
    process.stderr.write(
      'set KRN_CENSUS_CODING to the directory holding the census repositories, and TMPDIR to a disk path\n',
    );
    process.exit(64);
  }
  mkdirSync(SCRATCH, { recursive: true });
  const rows = POPULATION.map(census);
  const table = renderTable(rows);
  if (process.argv.includes('--write')) writeFileSync(TABLE, table);
  else process.stdout.write(table);
  rmSync(SCRATCH, { recursive: true, force: true });
}
