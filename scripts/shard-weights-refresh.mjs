// Shard weights from CI: folds the per-file wall times (`durationMs`) that each
// `Test (k/N)` job prints in its KRN_TEST_SUMMARY_JSON line into
// scripts/lib/shard-weights.mjs.
//   node scripts/shard-weights-refresh.mjs [--runs 5] [--repo owner/name] [--write]
// Prints the refreshed module (or writes it with --write); exits 1 when fewer
// than --runs successful main runs carry durations for every test job.
// Fetching needs an authenticated `gh`; the fold and render are pure.
import { execFileSync } from 'node:child_process';
import { realpathSync, writeFileSync } from 'node:fs';
import { relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TEST_FILE_WEIGHTS } from './lib/shard-weights.mjs';

const SUMMARY_PREFIX = 'KRN_TEST_SUMMARY_JSON=';
const WEIGHTS_PATH = fileURLToPath(
  new URL('./lib/shard-weights.mjs', import.meta.url),
);

// The summary JSON of one job log, or undefined when the job printed none.
export function parseJobSummary(logText) {
  for (const line of logText.split(/\r?\n/u)) {
    const at = line.indexOf(SUMMARY_PREFIX);
    if (at === -1) continue;
    return JSON.parse(line.slice(at + SUMMARY_PREFIX.length));
  }
  return undefined;
}

// CI reports absolute paths (/home/runner/work/krn/krn/test/x.test.ts).
export function repoTestPath(file) {
  if (file.startsWith('test/')) return file;
  const at = file.indexOf('/test/');
  return at === -1 ? file : file.slice(at + 1);
}

// Per-file durations (ms) of one run, or undefined when any shard summary is
// missing or lacks a duration for one of its files.
export function runDurations(summaries) {
  if (summaries.length === 0) return undefined;
  const durations = new Map();
  for (const summary of summaries) {
    if (!Array.isArray(summary?.files) || summary.files.length === 0)
      return undefined;
    for (const entry of summary.files) {
      if (!Number.isSafeInteger(entry?.durationMs)) return undefined;
      durations.set(repoTestPath(entry.file), entry.durationMs);
    }
  }
  return durations;
}

function median(values) {
  const sorted = [...values].sort((a, b) => a - b);
  const middle = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 1
    ? sorted[middle]
    : (sorted[middle - 1] + sorted[middle]) / 2;
}

// A weight is the median of a file's `durationMs` samples in seconds, to a
// tenth, at least 0.1: the unit and rounding every comparison with a weight
// must share (the drift section of shard-wall-report.mjs calls this too).
export function weightSeconds(durationsMs) {
  return Math.max(0.1, Math.round(median(durationsMs) / 100) / 10);
}

// Median seconds per file, to a tenth, at least 0.1. Files present now but
// absent from every run keep their previous weight; deleted files drop out.
export function foldShardWeights(runs, currentFiles, previous = {}) {
  const samples = new Map();
  for (const run of runs)
    for (const [file, ms] of run) {
      if (!samples.has(file)) samples.set(file, []);
      samples.get(file).push(ms);
    }
  const weights = {};
  const unmeasured = [];
  for (const file of [...currentFiles].sort()) {
    const values = samples.get(file);
    if (values) {
      weights[file] = weightSeconds(values);
    } else {
      unmeasured.push(file);
      if (previous[file] !== undefined) weights[file] = previous[file];
    }
  }
  return { weights, unmeasured };
}

export function renderWeightsModule(weights, sourceRuns) {
  const entries = Object.entries(weights)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([file, seconds]) => `  '${file}': ${seconds},`);
  return [
    '// Median wall time, in seconds, of each test file in CI test shards.',
    '// planTestShards balances shards by these weights so the slowest shard',
    '// bounds CI wall-clock; a file missing here falls back to its size.',
    '// Generated by `node scripts/shard-weights-refresh.mjs --write` from runs',
    `// ${sourceRuns.join(' ')}.`,
    'export const TEST_FILE_WEIGHTS = Object.freeze({',
    ...entries,
    '});',
    '',
  ].join('\n');
}

// One retry absorbs a transient connection reset from the GitHub API.
function gh(args, attempts = 2) {
  try {
    return execFileSync('gh', args, {
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
      stdio: ['ignore', 'pipe', 'pipe'],
    });
  } catch (error) {
    if (attempts <= 1) throw error;
    return gh(args, attempts - 1);
  }
}

// A job log line opens with its timestamp; the first line opens with a byte
// order mark before it.
// A step's log opens with `##[group]Run <command>`, a post step's with
// `Post job cleanup.`.
const LOG_LINE = /^\uFEFF?(\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(?:\.\d+)?Z) (.*)$/u;
const RUN_STEP = /^##\[group\]Run /u;
const POST_STEP = /^Post job cleanup\.$/u;

// Seconds, to a tenth, that the step which printed the summary line spans in a
// job log: from the last step start before that line to the first step or
// post step start after it. Undefined when the log lacks either boundary.
export function logStepSeconds(logText) {
  const lines = [];
  for (const line of logText.split(/\r?\n/u)) {
    const match = LOG_LINE.exec(line);
    if (match !== null)
      lines.push({ at: Date.parse(match[1]), text: match[2] });
  }
  const summary = lines.findIndex(({ text }) => text.includes(SUMMARY_PREFIX));
  if (summary === -1) return undefined;
  const start = lines
    .slice(0, summary)
    .findLast(({ text }) => RUN_STEP.test(text));
  const end = lines
    .slice(summary + 1)
    .find(({ text }) => RUN_STEP.test(text) || POST_STEP.test(text));
  if (start === undefined || end === undefined) return undefined;
  return Math.round((end.at - start.at) / 100) / 10;
}

// Seconds the job's `Run test shard` step took: its span in the job log, to a
// tenth, else its jobs API timing, which keeps whole seconds (a 19.7 s step
// reads 20 s) and so can flip a verdict within 1 s of a target; GitHub also
// sometimes returns a job with `steps: []`. Undefined when neither holds it.
export function testStepSeconds(job, logText = '') {
  const logged = logStepSeconds(logText);
  if (logged !== undefined) return logged;
  const step = job?.steps?.find((entry) => entry.name === 'Run test shard');
  if (step?.started_at && step?.completed_at)
    return (Date.parse(step.completed_at) - Date.parse(step.started_at)) / 1000;
  return undefined;
}

// The newest `wanted` successful main push runs whose every `Test (k/N)` job
// printed per-file durations:
// [{ id, headSha, jobs: [{ name, seconds, summary }] }].
// `select` narrows the listed runs ([{ databaseId, headSha }], newest first)
// before the newest `wanted` are taken, so a window never runs short because
// older runs came first; `runGh` stands in for the `gh` receiver.
export function fetchShardRuns(
  repo,
  wanted,
  { select = (listed) => listed, runGh = gh } = {},
) {
  const newest = JSON.parse(
    runGh([
      'run',
      'list',
      '--repo',
      repo,
      '--workflow',
      'ci.yml',
      '--branch',
      'main',
      '--event',
      'push',
      '--status',
      'success',
      '--limit',
      '40',
      '--json',
      'databaseId,headSha',
    ]),
  );
  const listed = select(newest);
  const runs = [];
  for (const { databaseId, headSha } of listed) {
    if (runs.length >= wanted) break;
    const jobs = JSON.parse(
      runGh([
        'api',
        `repos/${repo}/actions/runs/${databaseId}/jobs?per_page=100`,
      ]),
    ).jobs.filter((job) => job.name.startsWith('Test ('));
    if (jobs.length === 0) continue;
    const measured = [];
    for (const job of jobs) {
      const log = runGh([
        'api',
        '--allow-escape-sequences',
        `repos/${repo}/actions/jobs/${job.id}/logs`,
      ]);
      const summary = parseJobSummary(log);
      // One job without durations makes the whole run unusable.
      if (!runDurations([summary])) break;
      measured.push({
        name: job.name,
        seconds: testStepSeconds(job, log),
        summary,
      });
    }
    if (measured.length !== jobs.length) continue;
    runs.push({ id: String(databaseId), headSha, jobs: measured });
  }
  return runs;
}

function fetchRuns(repo, wanted) {
  const shardRuns = fetchShardRuns(repo, wanted);
  return {
    runs: shardRuns.map((run) =>
      runDurations(run.jobs.map((job) => job.summary)),
    ),
    ids: shardRuns.map((run) => run.id),
  };
}

async function main(argv) {
  let wanted = 5;
  let repo = 'krn-works/krn';
  let write = false;
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--write') write = true;
    else if (arg === '--runs') wanted = Number(argv[++index]);
    else if (arg === '--repo') repo = argv[++index];
    else throw new Error(`unknown argument: ${arg}`);
  }
  if (!Number.isSafeInteger(wanted) || wanted < 1)
    throw new Error('--runs must be a positive integer');
  const { runs, ids } = fetchRuns(repo, wanted);
  if (runs.length < wanted) {
    process.stderr.write(
      `shard-weights: ${runs.length} of ${wanted} main runs carry per-file durations\n`,
    );
    return 1;
  }
  const { selectTestFiles } = await import('./test-suite.mjs');
  const root = realpathSync(process.cwd());
  const current = selectTestFiles([], root).map((file) =>
    relative(root, file).split(sep).join('/'),
  );
  const { weights, unmeasured } = foldShardWeights(
    runs,
    current,
    TEST_FILE_WEIGHTS,
  );
  for (const file of unmeasured)
    process.stderr.write(`shard-weights: no CI samples, kept: ${file}\n`);
  const source = renderWeightsModule(weights, ids);
  if (write) writeFileSync(WEIGHTS_PATH, source);
  else process.stdout.write(source);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).then(
    (code) => {
      process.exitCode = code;
    },
    (error) => {
      process.stderr.write(`shard-weights: ${error.message}\n`);
      process.exitCode = 1;
    },
  );
}
